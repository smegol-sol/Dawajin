-- حارس تجميد لقطة الرصيد — القرار 223، تنفيذًا لنصّ §7-ب البند 45:
-- **«صفوف لقطة دورية تُكتب ولا تُعدَّل»**.
--
-- **والفهرس الفريد لا يُغني عنه:** `inventory_balance_snapshots_cut_uq` يمنع
-- **لقطةً ثانية بنفس الحدّ**، **ولا يمنع `UPDATE` يغيّر `balance` أو
-- `through_movement_id` على صفٍّ قائم**. **وصفٌّ معدَّل يُفسد كل قراءة بعده
-- بلا أن يصرخ شيء** — لأن القراءة تثق باللقطة ولا تعيد حسابها.
--
-- **ويُفرض في القاعدة لا في طبقة الخدمة** (درس القرار 203)، **وحارسٌ لا
-- `CHECK`** لأن الحكم على **الانتقال** (ما كان → ما صار) **والقيد يرى الصفّ
-- الجديد وحده**. نمط `system_product_guard` (القرار 213).
--
-- ═══ وتمييزٌ مقصود، وهو عكسُ معظم حرّاسنا فيُعلَّل ═══
--
-- **التعديل يُمنع · والحذف يبقى مسموحًا.**
--
-- **حرّاسنا تمنع الحذف عادةً** (`system_product_guard` يمنعه،
-- و`external_issue_order_freeze_guard` يمنعه) **لأن المحذوف هناك مصدرٌ يُبنى
-- عليه: صنفٌ نظاميّ تقوم عليه معادلة، وأمرُ صرفٍ هو سندُ حركة.**
--
-- **واللقطة ليست مصدرًا بل مشتقّة** — **والدفتر هو الحقيقة**: «تُحذف كلها
-- فيُعاد الحساب من الحركات بلا فقد»، **وهي الدعوى التي بُني عليها البند كله
-- وأُثبتت باختبار الحذف وإعادة الحساب**. **فمنعُ الحذف ينقض الدعوى** — يجعل
-- اللقطة صفًّا لا يُستغنى عنه، أي **مصدرًا** — **ومنعُ التعديل يحرسها**:
-- يبقى الصفّ إمّا صادقًا كما كُتب وإمّا غير موجود، **ولا حالة ثالثة يكذب فيها**.
--
-- **والقاعدة العامة:** يُمنع من المشتقّ **ما يجعله يكذب**، لا **ما يجعله
-- يختفي** — **فاختفاؤه يُعيد الحساب، وكذبُه يُفسده صامتًا**.
CREATE OR REPLACE FUNCTION "balance_snapshot_freeze_guard"()
RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'لقطة الرصيد تُكتب ولا تُعدَّل — احذفها ودعِ الحساب يعيدها من الدفتر (القرار 223، §7-ب البند 45)';
END;
$$ LANGUAGE plpgsql;--> statement-breakpoint

-- **`UPDATE` وحده في الأحداث** — **وغيابُ `DELETE` هنا هو الحكم لا سهوًا**:
-- انظر التعليل أعلاه.
CREATE TRIGGER "balance_snapshot_freeze_guard_trg"
BEFORE UPDATE ON "inventory_balance_snapshots"
FOR EACH ROW EXECUTE FUNCTION "balance_snapshot_freeze_guard"();
