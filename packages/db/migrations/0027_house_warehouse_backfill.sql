-- تعبئة مخازن العنابر القائمة — القرار 224، على حكم #161 «أولًا»:
-- **«مخزن العنبر واحد لكل عنبر ويُنشأ معه تلقائيًا»**.
--
-- **والتعبئة صريحةٌ في الترحيل لا في سكربت جانبي** (نمط القرار 205): سكربتٌ
-- خارجه **يُنسى على قاعدةٍ ويُشغَّل على أخرى**، **والحكم يقول «لكل عنبر» فلا
-- يحتمل عنبرًا بلا مخزن**.
--
-- **ولزومُها مقيسٌ لا مفترَض:** قاعدتا التطوير والاختبار **بلا مخزن عنبرٍ
-- واحد** مقابل عنابر قائمة — **فبلا هذه التعبئة يبقى كل عنبرٍ سابق بلا طرفٍ
-- للتحويل**، ويصير الحكم ساريًا على الجديد وحده.
--
-- **والاسم مشتقٌّ من اسم العنبر** — نفس اشتقاق `houseWarehouseName` في
-- `packages/db/src/seed/house-warehouse.ts`. **ومكرَّرٌ هنا عمدًا لأن القاعدة
-- لا تستورد TypeScript** (نفس علّة `ABSOLUTE_MIN_REST_DAYS` في القرار 197).
--
-- **و`WHERE NOT EXISTS` تجعلها قابلة لإعادة التشغيل** ولا تصطدم بالفهرس
-- الجزئي `warehouses_house_uq`.
INSERT INTO warehouses (tenant_id, name, level, house_id)
SELECT h.tenant_id, 'مخزن ' || h.name, 'عنبر', h.id
FROM houses h
WHERE NOT EXISTS (SELECT 1 FROM warehouses w WHERE w.house_id = h.id);
