import { describe, expect, it } from "vitest";

import { normalizePhoneE164 } from "./phone";

/**
 * الأربعة صيغ ذاتها المُثبتة سابقًا عبر apps/api (probe.integration.test.ts)
 * — هنا مباشرةً كوحدة معزولة، لتغطية 100% حقيقية داخل الحزمة المالكة.
 */
describe("normalizePhoneE164", () => {
  it("+967... يُقبل كما هو", () => {
    expect(normalizePhoneE164("+967771234567", "+967")).toBe("+967771234567");
  });

  it("00967... يتحول لـ+", () => {
    expect(normalizePhoneE164("00967771234567", "+967")).toBe("+967771234567");
  });

  it("محلي بصفر بادئ (0771...) يتطبّع بكود الدولة الافتراضي", () => {
    expect(normalizePhoneE164("0771234567", "+967")).toBe("+967771234567");
  });

  it("أرقام عربية-هندية (٠٧٧١٢٣٤٥٦٧) تُحوَّل قبل أي معالجة أخرى", () => {
    expect(normalizePhoneE164("٠٧٧١٢٣٤٥٦٧", "+967")).toBe("+967771234567");
  });

  it("رقم يبدأ برمز الدولة بلا + ولا صفر (967...) يُقبل مباشرة", () => {
    expect(normalizePhoneE164("967771234567", "+967")).toBe("+967771234567");
  });

  it("رقم وطني بلا صفر بادئ ولا رمز دولة (771234567) يُضاف له رمز الدولة", () => {
    expect(normalizePhoneE164("771234567", "+967")).toBe("+967771234567");
  });

  it("فواصل وأقواس ومسافات تُحذف قبل التطبيع", () => {
    expect(normalizePhoneE164("+967 77-123 (4567)", "+967")).toBe("+967771234567");
  });
});
