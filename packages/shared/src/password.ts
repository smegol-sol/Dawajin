/**
 * سياسة كلمة المرور — **مصدر واحد يقرأه الخادم والموبايل معًا**.
 *
 * كانت القيمة `8` مكتوبة حرفيًا في مخطط zod بالخادم، ومكرَّرة كثابت مستقل في
 * شاشة الموبايل. التكرار كان يعمل بالمصادفة لا بالبناء: تغيير الحد في الخادم
 * وحده كان يجعل الشاشة تعرض شرطًا كاذبًا للمستخدم، ويكتشفه برسالة خطأ بعد
 * الضغط — وهو بالضبط ما وُضع النص الإرشادي لمنعه (القرار #95).
 *
 * الحد يخصّ **مستخدمي المستأجر** (مربي/مشرف/طبيب/مالك). ومدير المنصة حدّه
 * **12 محرفًا** بثابت منفصل أدناه (القرار 195) — **ولا يُوحَّد الحدّان**:
 * سياسة المستأجرين تبقى كما هي، ورفعها قرار منتج لا أثر جانبي لبناء مسار آخر.
 */
export const MIN_PASSWORD_LENGTH = 8;

/**
 * حدّ كلمة مرور **مدير المنصة** — 12 محرفًا (backend-technical-spec.md §11،
 * والقرار #86، ونصّ القرار 187).
 *
 * **ثابت منفصل لا تعديل على الأول:** الحسابان مختلفان في الخطر والعدد —
 * حسابٌ **يرى كل المستأجرين** وحساباته ثلاثة يُنشأون بإجراء مباشر، مقابل
 * مستخدمي ميدان يُنشئهم المالك بالعشرات.
 */
export const PLATFORM_MIN_PASSWORD_LENGTH = 12;

/** رسالة رفض كلمة مرور المنصة القصيرة — بنفس صيغة رسالة المستأجرين. */
export const PLATFORM_PASSWORD_TOO_SHORT_MESSAGE = `كلمة المرور الجديدة يجب ألا تقل عن ${String(PLATFORM_MIN_PASSWORD_LENGTH)} محرفًا`;

/** رسالة الرفض العربية — نفس النص في تحقّق الخادم وفي الشاشة. */
export const PASSWORD_TOO_SHORT_MESSAGE = `كلمة المرور الجديدة يجب ألا تقل عن ${String(MIN_PASSWORD_LENGTH)} محارف`;

/** سطر الشروط المعروض تحت الحقل **قبل** الضغط لا بعده. */
export const PASSWORD_REQUIREMENTS_HINT = `${String(MIN_PASSWORD_LENGTH)} محارف على الأقل — لا شرط آخر`;
