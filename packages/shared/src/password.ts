/**
 * سياسة كلمة المرور — **مصدر واحد يقرأه الخادم والموبايل معًا**.
 *
 * كانت القيمة `8` مكتوبة حرفيًا في مخطط zod بالخادم، ومكرَّرة كثابت مستقل في
 * شاشة الموبايل. التكرار كان يعمل بالمصادفة لا بالبناء: تغيير الحد في الخادم
 * وحده كان يجعل الشاشة تعرض شرطًا كاذبًا للمستخدم، ويكتشفه برسالة خطأ بعد
 * الضغط — وهو بالضبط ما وُضع النص الإرشادي لمنعه (القرار #95).
 *
 * الحد يخصّ **مستخدمي المستأجر** (مربي/مشرف/طبيب/مالك). مدير المنصة حدّه 12
 * محرفًا بمسار دخول منفصل (backend-technical-spec.md §11، القرار #86) —
 * يُضاف ثابته هنا عند بناء ذلك المسار.
 */
export const MIN_PASSWORD_LENGTH = 8;

/** رسالة الرفض العربية — نفس النص في تحقّق الخادم وفي الشاشة. */
export const PASSWORD_TOO_SHORT_MESSAGE = `كلمة المرور الجديدة يجب ألا تقل عن ${String(MIN_PASSWORD_LENGTH)} محارف`;

/** سطر الشروط المعروض تحت الحقل **قبل** الضغط لا بعده. */
export const PASSWORD_REQUIREMENTS_HINT = `${String(MIN_PASSWORD_LENGTH)} محارف على الأقل — لا شرط آخر`;

// ═══════════════════════════════════════════════════════════════════
// الكلمة المؤقتة — تُولَّد على الخادم حصرًا، ولا تُكتب يدويًا أبدًا
// ═══════════════════════════════════════════════════════════════════

/**
 * أبجدية الكلمة المؤقتة — بلا محارف متشابهة بصريًا (`0/O`, `1/l/I`) لأنها
 * تُملى شفهيًا أو تُنسخ من شاشة المشرف، والخلط فيها يولّد بلاغات "لا تعمل"
 * لا اختراقًا. 32 محرفًا = 5 بتّات لكل محرف بالضبط.
 */
export const TEMP_PASSWORD_ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789#@";

/**
 * طول الكلمة المؤقتة. 12 محرفًا من أبجدية 32 ≈ 60 بتّة عشوائية — يجعل
 * التصادم بين كلمتين مؤقتتين مستحيلًا عمليًا، وهو **جوهر الإصلاح**: الثقب
 * الأمني (القرار #98) سببه تصادم كلمتين يدويتين لا آلية المقارنة.
 */
export const TEMP_PASSWORD_LENGTH = 12;

/** يطابق الشكل المولَّد حصرًا — الطول والأبجدية معًا. */
const GENERATED_TEMP_PASSWORD_PATTERN = new RegExp(
  `^[${TEMP_PASSWORD_ALPHABET.replaceAll("#", "\\#").replaceAll("@", "\\@")}]{${String(TEMP_PASSWORD_LENGTH)}}$`
);

/**
 * هل هذه الكلمة **مولَّدة** بالشكل المعتمد؟ حارس شكل لا حارس عشوائية —
 * لا يمكن لأي فحص إثبات أن قيمة ما خرجت من مولّد آمن، لكن رفض كل ما لا
 * يطابق الشكل يمنع الكلمات اليدوية القصيرة/المتكررة (`Temp1234`) وهي مصدر
 * الخطر الفعلي.
 * @returns true إن طابقت الطول والأبجدية المعتمدَين
 */
export function isGeneratedTemporaryPassword(candidate: string): boolean {
  return GENERATED_TEMP_PASSWORD_PATTERN.test(candidate);
}

/** رسالة الرفض عند تمرير كلمة مؤقتة غير مولَّدة. */
export const TEMP_PASSWORD_NOT_GENERATED_MESSAGE = "الكلمة المؤقتة تُولَّد آليًا ولا تُكتب يدويًا";
