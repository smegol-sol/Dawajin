import { describe, expect, it } from "vitest";

import { POWER_SOURCE } from "./enums";

/**
 * مصادر طاقة المزرعة (القرار #112). الاختبار على **القائمة كعقد**: القيمتان
 * بنصّهما هما ما يُخزَّن في نوع `power_source` في Postgres، فأي تعديل عليهما
 * يوجب ترحيلًا — والاختبار يجعل ذلك مرئيًا بدل أن يمرّ صامتًا.
 *
 * القيد «لا مزرعة بلا مصدر طاقة» مفروض في القاعدة (`NOT NULL` +
 * `cardinality >= 1`) ومُثبَت هناك بمخالفة متعمَّدة — ليس منطق تطبيق.
 */
describe("مصادر الطاقة", () => {
  it("قيمتان لا أربع — الحكومية والتجارية لا تصلان أماكن العنابر", () => {
    expect(POWER_SOURCE).toEqual(["شمسية", "مولدات"]);
  });

  it("بلا تكرار — القيمة المكرَّرة تفشل إنشاء نوع Postgres", () => {
    expect(new Set(POWER_SOURCE).size).toBe(POWER_SOURCE.length);
  });
});
