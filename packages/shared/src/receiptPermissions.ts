import { PRODUCT_CATEGORY, type ProductCategory, type UserRole } from "./enums";

/**
 * من يستلم من مورّد، وبأي فئة — **§12.2 صفّ «استلام من مورّد» وحده الحاكم**
 * (القرار 227).
 *
 * | الدور | ما يستلمه في §12.2 |
 * |---|---|
 * | `farmer` | ❌ |
 * | `supervisor` | ✅ **علف + مستلزمات تشغيل + معدات ومستلزمات إنشائية** |
 * | `vet` | ✅ **أدوية + لقاحات** |
 * | `owner` | ✅ **الكل** |
 * | `storekeeper` | ✅ **المركزي** |
 * | `platform_admin` | ❌ — **وليس في `USER_ROLE` أصلًا** (القراران #146
 *   و#147: مدير المنصة مفصولٌ بنيويًّا عن أدوار المستأجر)، فلا خانة له هنا |
 *
 * **وقائمة موجبة لا شرط سالب** (القرار 184): **دورٌ لا يُذكر لا يستلم شيئًا**،
 * **وفئةٌ تُضاف غدًا لا تدخل جيب أحد بالسكوت** — تُكتب في صفّها أو تبقى
 * للمالك وحده.
 */
export const RECEIPT_CATEGORIES_BY_ROLE: Readonly<Record<UserRole, readonly ProductCategory[]>> = {
  farmer: [],
  // **والمعدّات الإنشائية حكمُ مالكٍ صريح لا اشتقاق** (القرار 261): **قسمةُ
  // «مستلزمات» أسقطتها من يده إلى المالك بالاشتقاق وحده** — **فصُحِّح**.
  // **وعلّتُه ميدانية:** المشرف **يملك الصيانة والخدمات واستبدال الألواح
  // الشمسية** بحكم #154، **فمن يطلبها هو من يستلمها** — **وحصرُها في المالك
  // يوقف صيانةً حتى يفرغ لها**.
  //
  // **ويُكتب حكمًا كي لا ينقلب بقسمةٍ قادمة:** ما يقوم على الاشتقاق وحده
  // **يتبدّل كلما تبدّلت الفئات**، **وما يُكتب في صفّه يبقى**.
  supervisor: ["علف", "مستلزمات تشغيل", "معدات ومستلزمات إنشائية"],
  vet: ["دواء", "لقاح"],
  owner: PRODUCT_CATEGORY,
  // **§12.2 يعطيه «المركزي حصرًا» — وقيدُه مخزنٌ لا فئة**، فيستلم كلَّ فئةٍ
  // في مركزيّه المُسنَد. **والمخزن يفرضه الفرضُ المركزي لا هذه المصفوفة.**
  //
  // **وكان هنا نصٌّ يقول «ولا يبلغ هذا المسار اليوم» — وبطل بالقرار 254**
  // حين أُدرج في `ASSIGNMENT_SCOPED_ROLES` فصار يستلم فعلًا. **ويُكتب النسخُ
  // في موضعه لا محذوفًا** (المبدأ الرابع): **تعليقٌ في وحدةٍ مشتركة يوجّه من
  // يقرؤه** — وهو صنفُ ما أُغلق في `STATE.md` (القرار 261).
  storekeeper: PRODUCT_CATEGORY,
};

export function canReceiveCategory(role: UserRole, category: ProductCategory): boolean {
  return RECEIPT_CATEGORIES_BY_ROLE[role].includes(category);
}

/**
 * **فئتان لا يبلغهما إلا المالك** — **قراءةٌ للمصفوفة لا حكمٌ عليها**:
 * «فيتامين» و«معقمات ومطهرات» **ليستا في صفّ المشرف ولا الطبيب**، وصفّ
 * المالك «الكل» يشملهما. **يُسجَّل لأن سكوت المصفوفة عنهما قد يُقرأ سهوًا،
 * والقرار 184 يمنع منحهما بالسكوت** — فإن أُريد غيرُ ذلك فهو قرار مالك.
 *
 * **وصارت ثلاثًا يومًا واحدًا ثم عادت اثنتين** (القرار 261): **قسمةُ
 * «مستلزمات» أدخلت «معدات ومستلزمات إنشائية» هنا بالاشتقاق** — **ولم يقرّره
 * أحد** — **فأخرجها حكمُ المالك إلى صفّ المشرف**. **والحادثة تُكتب لأنها
 * تُري ما تفعله القسمةُ بالمشتقّات: تنقل صلاحيةً بلا أن يقرّرها أحد.**
 */
export const OWNER_ONLY_RECEIPT_CATEGORIES: readonly ProductCategory[] = PRODUCT_CATEGORY.filter(
  (category) =>
    !RECEIPT_CATEGORIES_BY_ROLE.supervisor.includes(category) &&
    !RECEIPT_CATEGORIES_BY_ROLE.vet.includes(category)
);
