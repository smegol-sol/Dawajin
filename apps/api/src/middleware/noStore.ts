import type { NextFunction, Request, Response } from "express";

/**
 * يمنع تخزين ردود المصادقة — **علاج سبب لا تعويض عنه** (القرار #177).
 *
 * **العطب مُقاس على الجهاز:** `GET /api/auth/me` عاد **`304` بلا جسم** ست مرات
 * متتالية، فتعذّر بناء المستخدم من ردٍّ فارغ **وقُرئت جلسة صالحة «تعذّر
 * اتصال»** — أي أن المستخدم كان يُحرم جلسته بسبب ذاكرة وسيطة لا بسبب رمزه.
 *
 * **والسبب `etag` الافتراضي في Express**: لا إعداد له في هذا المستودع إطلاقًا،
 * فردّ `/api/auth/me` يحمل `ETag: W/"84-..."` **وبلا `Cache-Control`** — مُثبَت
 * من ترويسات ردٍّ حقيقي في السجل. فالعميل يخزّن ثم يُعيد التحقق بـ
 * `If-None-Match`، فيردّ الخادم `304`.
 *
 * **وحذف `if-none-match` من الطلب مقصود ولازم**: `Cache-Control: no-store`
 * وحده يمنع **التخزين القادم** ولا يُبطل نسخة مخزَّنة **قبل** النشر — فأول
 * طلب بعده يصل ومعه `If-None-Match` فيعود `304` كما كان. حذفها يجعل الردّ
 * `200` بجسمه حتمًا.
 *
 * **ونطاقه مسارات المصادقة وحدها** — لا سياسة تخزين عامة للـAPI: ردود
 * المصادقة تحمل هوية صاحبها فلا تُخزَّن أصلًا، وبقية المسارات قرارها مستقل
 * لم يُتّخذ بعد.
 */
export function noStore(req: Request, res: Response, next: NextFunction): void {
  delete req.headers["if-none-match"];
  res.set("Cache-Control", "no-store");
  next();
}
