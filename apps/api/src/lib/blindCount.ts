import type { Role } from "./entityScope";

/**
 * **الاستلام الأعمى — حكمٌ على من يعدّ لا على مسارٍ بعينه** (القرار 286، على
 * §3.6 و160 «ثانيًا»).
 *
 * > **كلُّ رقمٍ متوقَّع يُحجب عن العادّ في كل مسار قراءةٍ حتى يعدّ** — **والحجبُ
 * > قبل العدّ لا بعده**: بعد التأكيد يُقرأ كلُّ شيء (العجزُ والمخصَّصُ والمشترى).
 *
 * **وحجبُه في الكتابة وحدها يجعله صوريًّا من أوّل مسار قراءةٍ يُبنى بعده** —
 * **ووقع مرتين في يومين** (القرار 281): `purchased_bird_count` في مسار
 * الدفعات، و`purchasedQuantity` في مسار قراءة الشحنة نفسِه.
 *
 * ## ورقمُ الحاوية يُحجب حتى تُعدّ كلُّ عِدادها
 *
 * > **رقمٌ متوقَّع على حاويةٍ فيها أكثر من عدّة يُحجب حتى تُعدّ كلُّها** —
 * > **فما دام يُشتقّ بالطرح فهو مكشوف.**
 *
 * **وهو حكمُ المالك بلفظه:** كشفُ المشترى وحصّةٌ لم تُعدّ بعدُ **يحدّ المتوقَّعَ
 * لها بالطرح** — **فالاستلام الأعمى ينكسر بحسابٍ لا بقراءة، وهو أخفى مما
 * نمنعه**.
 */

/**
 * **من يُطلب منه أن يعدّ في سلسلة الكتاكيت — المربّي وحده** (§12.2 صفّ «تأكيد
 * استلام حصة الكتاكيت»: `✅ عنابره` للمربّي و`❌` لما سواه).
 *
 * **وقائمةٌ موجبة لا شرطٌ سالب** (نمط `ASSIGNMENT_SCOPED_ROLES`): **دورٌ جديد
 * لا يصير عادًّا بالسكوت** — **والاتجاهُ هنا صحيح**: من لا يُدرَج **لا يُحجب
 * عنه شيء**، وهو من لا يُطلب منه العدّ أصلًا. **ويوم يُطلب من دورٍ أن يعدّ
 * يُدرَج هنا بقرار مكتوب.**
 */
const CHICK_COUNTERS = new Set<Role>(["farmer"]);

export function isChickCounter(role: Role): boolean {
  return CHICK_COUNTERS.has(role);
}

/**
 * **هل اكتمل عدُّ ما يراه هذا العادّ؟**
 *
 * **يُسأل على الصفوف المرئية له وحدها** — فحصّةُ عنبرٍ لا يبلغه لا تحجب عنه
 * شيئًا ولا تُقرأ له.
 *
 * @param rows التوزيعات المرئية للرائي، بحقل «متى أُكِّدت»
 * @returns صحيحٌ حين لا يبقى فيها ما لم يُؤكَّد — **وحين لا صفَّ أصلًا**
 */
export function countingComplete(rows: readonly { confirmedAt: Date | null }[]): boolean {
  return rows.every((row) => row.confirmedAt !== null);
}

/**
 * **مستقبِلُ التحويل الأعمى — عادٌّ يُعرَف بموضعه من الشحنة لا بدوره** (القرار
 * 288، على 286 و#159 «رابعًا»).
 *
 * **والعادُّ هنا ليس دورًا واحدًا:** المؤكِّد يتبع **مستوى المخزن المستلِم**
 * (`assertWarehouseOwner`) — مخزنُ العنبر لمربّيه، ومخزنُ الموقع لمشرفه،
 * والمركزيُّ لأمين مخزنه. **فقائمةُ أدوارٍ لا تصفه**، والوصفُ الصادق: **من
 * يبلغه هذا التحويل من جهة الوجهة وحدها**.
 *
 * **و«وحدها» هي الشرط كلُّه — لا زيادةَ احتياط:**
 *
 * - **من يرى المصدر يقرأ الكمية من دفتره** على أي حال (حركةُ «تحويل صادر»
 *   بالكمية المُصدَرة) — **فحجبُها عنه حجبٌ صوريّ**، **وهو بعينه ما نقضه
 *   القرار 286** («فما دام يُشتقّ بالطرح فهو مكشوف»).
 * - **والمالك يرى كلَّ مخزن** (`visibleWarehouseCondition` تُرجع `allowAll`)
 *   **فـ`viaSource` صحيحٌ له في كل صفّ** — **فلا يُستثنى بشرطٍ على دوره، بل
 *   يخرج بالبناء**. **وهذا مقصود:** استثناءٌ على الدور يعود ثقبًا يوم يُضاف
 *   دورٌ ذو رؤيةٍ كاملة.
 *
 * **واتجاهُ السكوت صحيح (القرار 276):** من لا ينطبق عليه الشرط **لا يُحجب عنه
 * شيء** — **ومنهم من يبلغه المخزن المستلِم ولا يملكه** (طبيبُ المزرعة يرى
 * مخزن العنبر ولا يؤكّد فيه). **فالحجبُ يشمله وهو ليس عادًّا** — **زيادةٌ في
 * الحجب لا ثقبٌ فيه**، **وثمنُها ألّا يُعاد كتابةُ حكم الملكية في SQL**.
 *
 * **ولا شرطَ «حتى يعدّ» هنا لأن السرد نفسَه مشروطٌ به:** `listInTransit` لا
 * يُرجع إلا «في الطريق»، **فالصفُّ يغادر السردَ بالتأكيد لا يُقرأ فيه**.
 * **والقراءةُ بعد العدّ في ردّ التأكيد** (`issuedQuantity`) — **وهو الطرف
 * الثاني من الزوج الذي يثبت أن الشرط يعمل**.
 *
 * @param row موضعُ الرائي من الشحنة — أيبلغه طرفُها المرسِل، أم وجهتُها، أم كلاهما
 * @returns صحيحٌ حين تُحجب الكمية المُصدَرة عن هذا الرائي في هذا الصفّ
 */
export function hidesIssuedQuantity(row: { viaSource: boolean; viaDestination: boolean }): boolean {
  return row.viaDestination && !row.viaSource;
}
