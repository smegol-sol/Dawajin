import { useState } from "react";

/**
 * **رسائلُ النقص المعروضة — تُكتب عند الضغط وتُمحى عند إصلاح حقلها وحده**
 * (القرار 294، **وهو الوجه الثاني لحكم 292 لا عطبٌ مستقلّ**).
 *
 * **والقاعدةُ طرفان لا واحد:**
 *
 * 1. **لا حمرةَ قبل الضغط** (292) — فصفٌّ يُضاف للتوّ لا يُستقبَل بالحمرة.
 * 2. **ولا حمرةَ بعد أن يزول موجبُها** (294) — **فرسالةٌ تحت حقلٍ مملوء
 *    تكذب على قارئها**.
 *
 * **ومن يقرأ أحدهما يقرأ الآخر** — ولذلك هما في قرارٍ واحد لا قرارين.
 *
 * ## والعطبُ الذي أوجب هذا الملف — رآه المالك على جهازه
 *
 * حقلُ «كلمة المرور الحالية» **مملوءٌ بأحد عشر محرفًا وتحته «أدخل كلمة المرور
 * الحالية»**. **والعلّة أن `setError` لم يكن يُستدعى إلا في `handleSubmit`** —
 * **فلا مسارَ واحدٌ يمحو الرسالة عند الكتابة**، **في أربع شاشات بنفس الشكل**.
 *
 * **ومرّ في تجربةٍ كنّا نفحصها بالذات:** في تجربة 292 **اختار المالك الصنف
 * فعاد الزرُّ أخضر، والعلامةُ الحمراء باقيةٌ تحت الحقل الذي أصلحه** — **ولم
 * ننتبه لأن الزرَّ سرق النظر**. **فحتى العين المستعمِلة تُخطئ حين ينافس
 * عنصرٌ عنصرًا.**
 *
 * ## والمحوُ بالمفتاح لا بأيّ كتابة
 *
 * **`clear` يمحو ما يطابق مفتاحَه ويُبقي ما سواه** — **وهذا هو ما يمنع علاجًا
 * يمحو كلَّ شيء عند أيّ كتابة** (حكم المالك). **وشاهدُه يفرّق بالطرف الثاني:
 * الكتابةُ في حقلٍ آخر لا تمحو رسالةَ الأول.**
 *
 * **وحدٌّ معلَن (القرار 268): رسالةُ النموذج كلِّه** (`form`) — كخطأ الشبكة أو
 * ردِّ الخادم — **لا يمحوها حقلٌ لأنها لا تخصّ حقلًا**، **فتبقى حتى الضغطة
 * التالية**. **يسقط الحدُّ يوم تُسنَد رسالةُ خادمٍ إلى حقلها** (مثل «كلمة
 * المرور الحالية غير صحيحة»، وهي اليوم `form`).
 *
 * @param keyOf مفتاحُ الحقل الذي يخصّه الخطأ — **دالّةُ الشاشة لا معرفةُ هذا
 *   الملف بشكل الخطأ**، فيخدم شكلَي الخطأ في المستودع بلا أن يعرف أيًّا منهما.
 */
export function useFieldErrors<E>(keyOf: (error: E) => string): {
  shown: readonly E[];
  show: (found: readonly E[]) => void;
  clear: (...keys: readonly string[]) => void;
  bind: <V>(key: string, write: (value: V) => void) => (value: V) => void;
} {
  const [shown, setShown] = useState<readonly E[]>([]);

  const clear = (...keys: readonly string[]): void => {
    if (keys.length === 0) return;
    setShown((current) => current.filter((error) => !keys.includes(keyOf(error))));
  };

  return {
    shown,
    show: setShown,
    clear,
    /** **يكتب القيمة ثم يمحو رسالةَ هذا الحقل وحده** — غلافٌ للحالة البسيطة. */
    bind:
      <V>(key: string, write: (value: V) => void) =>
      (value: V): void => {
        write(value);
        clear(key);
      },
  };
}
