import { I18nManager } from "react-native";

/**
 * يجب أن يكون هذا أول استيراد في app/_layout.tsx — التطبيق عربي بالكامل
 * باتجاه RTL (docs/app-complete-spec.md §1 و§10). استيرادات ES تُرفع
 * (hoisted) بحيث تُنفَّذ كل الاستيرادات قبل أي كود آخر في الملف، لذا وضع
 * هذا الفرض كعبارة عادية داخل _layout.tsx لا يضمن تنفيذه أولًا — فقط جعله
 * *أول استيراد* في سلسلة استيرادات متعاقبة يضمن ذلك.
 *
 * لا يُطبَّق فعليًا على الجهاز إلا بعد إعادة تحميل حزمة JS، فقد يحتاج
 * المستخدم إعادة فتح التطبيق في أول تشغيل.
 */
if (!I18nManager.isRTL) {
  I18nManager.allowRTL(true);
  I18nManager.forceRTL(true);
}
