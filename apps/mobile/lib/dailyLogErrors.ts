import { DailyLogRequestError } from "./dailyLogApi";

/**
 * **رسالةٌ عربية لكل فشلٍ في شاشة السجل اليوميّ** — **تُكتب هنا بالرمز ولا
 * تُنقَل من الخادم خامًا** (نمط `infrastructureErrors`): الرمزُ عقدٌ ثابت،
 * **وصياغةُ ما يقرؤه المربّي تخصّ الشاشة**؛ **والرسالة الخام لا تصل أصلًا**
 * — `toApiFailure` يحمل الحالة والرمز وحدهما.
 *
 * **و«لا دفعة نشطة» غائبةٌ من هنا عمدًا:** الشاشةُ تقرأ الدفعة **قبل** أن
 * تعرض النموذج، **فتُظهر الحالة الفارغة بدل نموذجٍ يُرفض** — **وبقاؤها في
 * الجدول أدناه احتياطٌ لسباقٍ حقيقيّ**: دفعةٌ تُغلَق بين التحميل والحفظ.
 */

/** رفضٌ بحكمٍ معلوم — **رُفض الطلب لا انهار** (نمط القرار 226). */
const REJECTION: Record<string, string> = {
  no_active_batch: "لم تعد في عنبرك دفعة نشطة — أعد فتح الشاشة",
  product_not_feed: "الصنف المختار ليس علفًا بوحدة الكيس",
  product_missing_package_size: "صنف العلف بلا وزن عبوة — راجع مشرفك",
  sample_pair_required: "عيّنة الوزن رقمان معًا: عدد الطيور ووزنها",
  house_without_tank_capacity: "العنبر بلا سعة خزان — فالماء لا يُسجَّل فيه",
};

/**
 * **الحالاتُ ذاتُ النصّ الواحد — جدولٌ لا سلسلةُ شروط** (`complexity`، والحدّ
 * يُحترم بالفصل لا برفعه). **و409 منها**: سجلُّ اليوم محفوظٌ سلفًا **واقعةٌ
 * متوقَّعة لا عطب** (§14.1) — المربّي سجّل صباحًا وعاد مساءً.
 */
const BY_STATUS: Record<number, string> = {
  401: "انتهت الجلسة — سجّل الدخول من جديد",
  403: "لم يعد هذا العنبر ضمن ما أُسند إليك",
  404: "لم يعد موجودًا — ربما حُذف",
  409: "سجل اليوم محفوظ بالفعل — لا يُسجَّل يومان لنفس الدفعة",
};

export function dailyLogErrorMessage(error: unknown): string {
  if (!(error instanceof DailyLogRequestError)) return "تعذّر تنفيذ الطلب — أعد المحاولة";

  const { status, code } = error.failure;
  if (status === null) return "تعذّر الاتصال بالخادم — تحقّق من الشبكة ثم أعد المحاولة";
  if (status === 422)
    return (code === null ? undefined : REJECTION[code]) ?? "رُفض الطلب — راجع ما أدخلته";
  return BY_STATUS[status] ?? "تعذّر تنفيذ الطلب — أعد المحاولة";
}
