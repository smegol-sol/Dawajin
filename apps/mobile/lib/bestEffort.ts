/**
 * يتجاهل فشل عملية غير حرجة صراحةً — بديل موثَّق عن `.catch(() => {})`
 * المجهول، الذي يُخفي نيّة المطوّر: هل الفشل مقبول فعلًا أم أن المعالجة
 * نُسيت؟ (وهو بالضبط ما تحرسه قاعدة no-empty-function.)
 *
 * يُستخدم حصريًا حين يكون فشل العملية غير مؤثر على المستخدم — مثل إخفاء
 * شاشة البداية: إن فشل، تبقى الشاشة ظاهرة لحظة إضافية لا أكثر.
 *
 * @param operation الوعد الذي يُتجاهل فشله
 */
export function bestEffort(operation: Promise<unknown>): void {
  operation.catch(() => {
    // مقصود: فشل غير حرج لا يستدعي تعطيل التطبيق ولا إزعاج المستخدم
  });
}
