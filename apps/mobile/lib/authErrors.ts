/**
 * تصنيف فشل تسجيل الدخول إلى رسالة عربية جاهزة للعرض **تحت الحقل** لا أعلى
 * الشاشة (docs/app-complete-spec.md §8.11). مفصول عن طبقة الشبكة وعن الشاشة
 * معًا كي يكون قابلًا للاختبار وحده بلا تصيير ولا خادم.
 *
 * القاعدة الحاكمة (§8.17 و§11): **حالة الخطأ تعرض السبب لا رسالة عامة.**
 */

/** الحقل الذي تُعرض الرسالة تحته — النموذج لا يعرض خطأً أعلى الشاشة أبدًا. */
export type LoginErrorField = "phone" | "password" | "form";

export interface LoginErrorView {
  field: LoginErrorField;
  message: string;
}

/**
 * شكل الفشل كما تراه الشاشة، مستخلَصًا من استجابة axios في طبقة الـAPI.
 * `status: null` يعني أن الطلب لم يصل الخادم إطلاقًا (انقطاع شبكة) — وهو
 * تمييز جوهري: 500 من الخادم ليس انقطاع شبكة، ورسالتاهما مختلفتان.
 */
export interface LoginFailure {
  status: number | null;
  code: string | null;
}

/**
 * الحالات الأربع المطلوبة على شاشة الدخول، ولا واحدة منها رسالة عامة:
 * بيانات خاطئة · حساب معطّل · تجاوز المحاولات · انقطاع الشبكة.
 * @returns الحقل الذي تُعرض تحته الرسالة، ونصّها العربي
 */
export function loginErrorView(failure: LoginFailure): LoginErrorView {
  // انقطاع الشبكة أولًا: لا استجابة أصلًا، فلا status ولا code يُقرآن
  if (failure.status === null) {
    return {
      field: "form",
      message: "تعذّر الاتصال بالخادم — تحقّق من الشبكة في العنبر ثم أعد المحاولة",
    };
  }

  if (failure.status === 429) {
    return {
      field: "form",
      message: "محاولات كثيرة — انتظر دقيقة ثم أعد المحاولة",
    };
  }

  // كلمة المرور صحيحة والحساب معطَّل (القرار #84) — رسالة تقول للمربي ماذا
  // يفعل، بدل تركه يظن أنه نسي كلمة مروره
  if (failure.status === 403 && failure.code === "account_disabled") {
    return {
      field: "form",
      message: "حسابك معطّل — راجع المشرف",
    };
  }

  if (failure.status === 401) {
    // تحت حقل كلمة المرور: هو الحقل الذي يُعاد إدخاله عمليًا، والرسالة
    // نفسها تبقى عامة لا تكشف أي الحقلين خاطئ (§11)
    return {
      field: "password",
      message: "رقم الجوال أو كلمة المرور غير صحيحة",
    };
  }

  // أي فشل خادم آخر — يُعرض سببه (رمز الحالة) لا "حدث خطأ ما"
  return {
    field: "form",
    message: `تعذّر تسجيل الدخول — استجابة غير متوقّعة من الخادم (${String(failure.status)})`,
  };
}

/** رسائل التحقق المحلي قبل إرسال الطلب — تُعرض تحت حقلها هي أيضًا. */
export const LOGIN_VALIDATION = {
  phoneRequired: "أدخل رقم الجوال",
  passwordRequired: "أدخل كلمة المرور",
  /**
   * لا حساب لهذا الرقم. يكشف أن الرقم غير مسجَّل — تسريب مقبول صراحةً في
   * القرار #106 وموازنته: أخفّ بمراتب من الاستيلاء الكامل الذي كان ممكنًا،
   * والبديل (رسالة غامضة ثم شاشة كلمة مرور لحساب غير موجود) يترك المستخدم
   * يجرّب كلمات مرور لرقم خاطئ بلا سبب مفهوم.
   */
  phoneNotRegistered: "لا يوجد حساب بهذا الرقم — راجع المشرف",
} as const;
